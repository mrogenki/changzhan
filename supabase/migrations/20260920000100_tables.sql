create table if not exists public.signup_sheets (
  id bigint generated by default as identity not null,
  -- 公開連結用隨機 token，不用流水號 id（不然網址數字加一就能看到別人的接龍）。
  -- URL-safe base64：一般 base64 的 '+' 在 query string 會被解成空白。
  token text default translate(encode(extensions.gen_random_bytes(9), 'base64'::text), '+/'::text, '-_'::text) not null,
  title text not null,
  description text,
  activity_id bigint,
  deadline timestamp with time zone,
  max_people integer,
  allow_guests boolean default true not null,
  allow_non_members boolean default true not null,
  status text default 'open'::text not null,
  created_by text,
  created_at timestamp with time zone default now() not null,
  fee integer default 0 not null,
  member_fee integer
);

-- 序列的擁有者接回欄位，日後 drop table 時序列才會一起消失
alter sequence public.documents_id_seq owned by public.documents.id;
alter sequence public.guests_id_seq owned by public.guests.id;
alter sequence public.message_send_log_id_seq owned by public.message_send_log.id;
alter sequence public.milestones_id_seq owned by public.milestones.id;
