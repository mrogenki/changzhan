-- ⚠️ 不含 bni-report 獨佔的表（palms_imports / traffic_light_imports / member_groups）
--    與兩系統共用的 user_roles。新分會如果不跑 bni-report，就不需要它們。

-- signup_sheets.token 的預設值用到 pgcrypto 的 gen_random_bytes()。
-- Supabase 把擴充套件裝在 extensions schema，不在預設 search_path 裡，
-- 所以要明確指定 schema，否則在乾淨的新專案上會噴
-- 「function gen_random_bytes(integer) does not exist」。
create extension if not exists pgcrypto with schema extensions;

-- 早期用 serial 建的表，預設值是 nextval()，所以序列要先存在
create sequence if not exists public.documents_id_seq;
create sequence if not exists public.guests_id_seq;
create sequence if not exists public.message_send_log_id_seq;
create sequence if not exists public.milestones_id_seq;

